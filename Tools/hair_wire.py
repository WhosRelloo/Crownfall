"""Wire hairstyles into the game (Docs/Plans/2026-10-28-class-origin-traits-hair.md, section 5).

    python Tools/hair_wire.py data                    # Shared/HairData.luau only (the style list per body)
    python Tools/hair_wire.py export <build_dir>      # upload-ready files in E:/Crownfall/Uploads
    python Tools/hair_wire.py wire <build_dir> <ids.json>
                                                      # after uploading: manifests, class maps, hair modules

ids.json maps each uploaded file's name (without .png) to its asset id, e.g. {"MBaldWalk (South)": 1234, ...};
Tools/hair_wire.py ids <export dir> writes a template to fill in. "wire" switches the game to the bald bodies plus
hair layers in one go, so nothing ever shows a bald body without its hair.
"""
import json
import re
import os
import shutil
import sys

from PIL import Image

import hair

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SRC = os.path.join(ROOT, "src", "ReplicatedStorage", "Crownfall")
RIG = {"m": "humanm", "f": "humanf"}
LETTER = {"m": "M", "f": "F"}
ANIMS = [("idle", "Idle", 6, "Loop"), ("walk", "Walk", 10, "Loop"), ("run", "Run", 12, "Loop"), ("dodge", "Dodge", 20, "Once")]
ROWS = ["S", "SW", "W", "NW", "N", "NE", "E", "SE"]
NAMES = {"S": "South", "SW": "South-West", "W": "West", "NW": "North-West",
         "N": "North", "NE": "North-East", "E": "East", "SE": "South-East"}
UPLOADS = "E:/Crownfall/Uploads"


def strip_name(body, anim_label, d):
    return f"{LETTER[body]}Bald{anim_label} ({NAMES[d]})"


def hair_name(body, style_name):
    return f"Hair {LETTER[body]} {style_name}"


def write_data():
    lines = ["-- GENERATED by Tools/hair_wire.py from Tools/hair.py: the hairstyles per body, in creator order.",
             "-- The first is the body's default (the hair it was first drawn with).", "return {"]
    for body in "mf":
        lines.append(f"\t{body} = {{")
        for sid, name, _ in hair.STYLES[body]:
            lines.append(f'\t\t{{ Id = "{sid}", Name = "{name}" }},')
        lines.append("\t},")
    lines.append("}")
    path = os.path.join(SRC, "Shared", "HairData.luau")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


def export(build):
    os.makedirs(UPLOADS, exist_ok=True)
    for body in "mf":
        for anim, label, _, _ in ANIMS:
            sheet = Image.open(os.path.join(build, f"{RIG[body]}_bald_{anim}.png")).convert("RGBA")
            for r, d in enumerate(ROWS):
                sheet.crop((0, r * 96, 768, (r + 1) * 96)).save(os.path.join(UPLOADS, strip_name(body, label, d) + ".png"))
        for sid, name, _ in hair.STYLES[body]:
            shutil.copy(os.path.join(build, f"hair_{RIG[body]}_{sid}.png"), os.path.join(UPLOADS, hair_name(body, name) + ".png"))
    print("wrote", UPLOADS, len(os.listdir(UPLOADS)), "files")


def rle(img):
    px = img.load()
    out, prev, n = [], None, 0
    for y in range(img.height):
        for x in range(img.width):
            k = px[x, y]
            if k == prev:
                n += 1
                continue
            if prev is not None:
                out.append("abcdefg"[prev] + (str(n) if n > 1 else ""))
            prev, n = k, 1
    out.append("abcdefg"[prev] + (str(n) if n > 1 else ""))
    return "".join(out)


def wire(build, ids_path):
    import class_maps
    import recolour

    with open(ids_path, encoding="utf-8") as f:
        ids = json.load(f)
    missing = [k for k in ids if not ids[k]]
    assert not missing, f"no id yet for: {missing}"
    # manifests: every animation one strip per direction, the bald body
    for body in "mf":
        rig = RIG[body]
        lines = [f"-- Art manifest: {'male' if body == 'm' else 'female'} human, bald body (hair is a separate layer,",
                 "-- Render/Hair). GENERATED by Tools/hair_wire.py; IDs from Art/Sprites/asset-ids.json.",
                 "return {", '\tKind = "Sheet",', f'\tRig = "{rig}",', '\tOutfit = "rags",', "\tCell = 96, -- px",
                 "\tPivot = Vector2.new(48, 88), -- standard feet point, px from the cell's top-left",
                 "\tStudsPerPixel = 5 / 64, -- 64 px character = 5 studs", "\tAnims = {"]
        for anim, label, fps, mode in ANIMS:
            lines += [f"\t\t{anim} = {{", "\t\t\tFrames = 8,", f"\t\t\tFPS = {fps},", f'\t\t\tMode = "{mode}",', "\t\t\tImages = {"]
            for d in ROWS:
                lines.append(f'\t\t\t\t{d} = "rbxassetid://{ids[strip_name(body, label, d)]}",')
            lines += ["\t\t\t},", "\t\t},"]
        lines += ["\t},", "\tLayers = { full = { rags = {} } },", "}"]
        with open(os.path.join(SRC, "Render", "Art", f"{rig}.luau"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        # body class maps from the bald sheets
        pairs = {}
        for anim, _, _, _ in ANIMS:
            sheet = Image.open(os.path.join(build, f"{rig}_bald_{anim}.png")).convert("RGBA")
            classes = Image.open(os.path.join(build, f"{rig}_bald_{anim}_classes.png"))
            pairs[anim] = (sheet, classes.copy())
        class_maps.write_maps(rig, pairs)
        ranges = recolour.stats(pairs.values())
        # hair modules
        hair_dir = os.path.join(SRC, "Render", "Hair")
        os.makedirs(hair_dir, exist_ok=True)
        for sid, name, _ in hair.STYLES[body]:
            with open(os.path.join(build, f"hair_{rig}_{sid}.json")) as f:
                meta = json.load(f)
            classes = Image.open(os.path.join(build, f"hair_{rig}_{sid}_classes.png"))
            rects = ";".join(",".join(str(v) for v in r) for r in meta["rects"])
            lines = [f"-- GENERATED by Tools/hair_wire.py: the {name} hair layer for {rig}. Frames in order idle, walk, run,",
                     "-- dodge; S SW W NW N NE E SE; frames 1-8. Each: atlas x, y, w, h, then where it sits in the 96 px cell.",
                     "return {",
                     f'\tImage = "rbxassetid://{ids[hair_name(body, name)]}",',
                     f"\tSize = Vector2.new({meta['size'][0]}, {meta['size'][1]}),",
                     f'\tRects = "{rects}",',
                     f'\tClasses = "{rle(classes)}",',
                     "}"]
            with open(os.path.join(hair_dir, f"{rig}_{sid}.luau"), "w", encoding="utf-8", newline="\n") as f:
                f.write("\n".join(lines) + "\n")
        # hair colour is recoloured over the hair layers' range (the bald body only has brows and stubble)
        vals = []
        for sid, _, _ in hair.STYLES[body]:
            atlas = Image.open(os.path.join(build, f"hair_{rig}_{sid}.png")).convert("RGBA").load()
            cls = Image.open(os.path.join(build, f"hair_{rig}_{sid}_classes.png"))
            cp = cls.load()
            for y in range(cls.height):
                for x in range(cls.width):
                    if cp[x, y] == 4:
                        c = atlas[x, y]
                        vals.append(0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2])
        vals.sort()
        lo, hi = round(vals[int(0.02 * (len(vals) - 1))], 1), round(vals[int(0.98 * (len(vals) - 1))], 1)
        index = os.path.join(SRC, "Render", "ClassMaps", f"{rig}.luau")
        text = open(index, encoding="utf-8").read()
        text = re.sub(r"hair = \{ [0-9.]+, [0-9.]+ \}", f"hair = {{ {lo}, {hi} }}", text)
        with open(index, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wired", rig, "hair range from the hair layers", (lo, hi))
    write_data()


def ids_template(folder):
    names = sorted(os.path.splitext(n)[0] for n in os.listdir(folder) if n.endswith(".png"))
    path = os.path.join(folder, "ids.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump({n: 0 for n in names}, f, indent=1)
    print("wrote", path)


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "data":
        write_data()
    elif cmd == "export":
        export(sys.argv[2])
    elif cmd == "wire":
        wire(sys.argv[2], sys.argv[3])
    elif cmd == "ids":
        ids_template(sys.argv[2])
