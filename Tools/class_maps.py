"""Build the game data for character customization.

    python Tools/class_maps.py [--write-female]

1. Rebuilds every sheet with colour classes (Tools/walk_cycle.py --classes):
   - male (humanm): walk, run and dodge from Art/Source/cf_human_m_full_rags_walk_v2.zip;
   - female (humanf): idle, walk, run and dodge from the female base poses Tools/female.py draws from that zip.
   Each rebuilt sheet must match the one in Art/Sprites/<rig> byte for byte (those are the uploaded images).
   --write-female writes the female sheets there instead, after a deliberate change to the female art.
2. Writes src/ReplicatedStorage/Crownfall/Render/ClassMaps/<rig>*.luau: one run-length class map per direction
   strip, plus each class's brightness range.
3. Writes src/ReplicatedStorage/Crownfall/Shared/AppearanceData.luau from Art/Sprites/palettes.json.
"""
import os
import subprocess
import sys
import tempfile
import zipfile

from PIL import Image

import colour_classes as C
import recolour

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
ZIP = os.path.join(ROOT, "Art", "Source", "cf_human_m_full_rags_walk_v2.zip")
SPRITES = os.path.join(ROOT, "Art", "Sprites")
OUT_MAPS = os.path.join(ROOT, "src", "ReplicatedStorage", "Crownfall", "Render", "ClassMaps")
OUT_DATA = os.path.join(ROOT, "src", "ReplicatedStorage", "Crownfall", "Shared", "AppearanceData.luau")
ROWS = ["S", "SW", "W", "NW", "N", "NE", "E", "SE"]
BODIES = {  # rig -> (base-pose prefix, styles with stored maps; the male idle is classified in game)
    "humanm": ("cf_human_m_full_rags_walk", ["walk", "run", "dodge"]),
    "humanf": ("cf_human_f_full_rags_walk", ["idle", "walk", "run", "dodge"]),
}
CELL = 96
LETTERS = "abcdefg"  # class 0..6


def rle(classes, top):
    """One 768 x 96 strip, row-major: a class letter, then the run length when more than 1 ('a12c3e')."""
    px = classes.load()
    out, prev, n = [], None, 0
    for y in range(top, top + CELL):
        for x in range(classes.width):
            k = px[x, y]
            if k == prev:
                n += 1
                continue
            if prev is not None:
                out.append(LETTERS[prev] + (str(n) if n > 1 else ""))
            prev, n = k, 1
    out.append(LETTERS[prev] + (str(n) if n > 1 else ""))
    return "".join(out)


def build(rig, src, scratch, write):
    prefix, styles = BODIES[rig]
    pairs = {}
    for style in styles:
        sheet_out = os.path.join(scratch, f"{rig}_{style}.png")
        class_out = os.path.join(scratch, f"{rig}_{style}_classes.png")
        subprocess.run([sys.executable, os.path.join(HERE, "walk_cycle.py"), src, sheet_out, "--style", style,
                        "--prefix", prefix, "--classes", class_out], check=True, stdout=subprocess.DEVNULL)
        with Image.open(sheet_out) as im:
            built = im.convert("RGBA")
        kept = os.path.join(SPRITES, rig, f"cf_{rig}_full_rags_{style}.png")
        if write:
            os.makedirs(os.path.dirname(kept), exist_ok=True)
            built.save(kept)
            print("wrote", kept)
        with Image.open(kept) as im:
            uploaded = im.convert("RGBA")
        assert built.tobytes() == uploaded.tobytes(), f"{rig} {style}: rebuilt sheet differs from {kept}"
        with Image.open(class_out) as im:
            pairs[style] = (uploaded, im.copy())
    return pairs


def lua_ramp(ramp):
    return "{ " + ", ".join(f"Color3.fromRGB({r}, {g}, {b})" for r, g, b in ramp) + " }"


def write_data():
    pal = recolour.load_palettes()
    lines = [
        "-- GENERATED by Tools/class_maps.py from Art/Sprites/palettes.json. Do not edit by hand.",
        "-- Curated colour sets for character customization; each ramp runs dark to light.",
        "return {",
    ]
    for slot in ("skin", "hair", "outfit"):
        lines.append(f"\t{slot} = {{")
        for e in pal[slot]:
            orig = ", Original = true" if e.get("original") else ""
            lines.append(f'\t\t{{ Id = "{e["id"]}", Name = "{e["name"]}"{orig}, Ramp = {lua_ramp(e["ramp"])} }},')
        lines.append("\t},")
    lines.append("}")
    with open(OUT_DATA, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT_DATA)


def write_maps(rig, pairs):
    ranges = recolour.stats(pairs.values())
    for style, (sheet, classes) in pairs.items():
        lines = [f"-- GENERATED by Tools/class_maps.py: colour classes for {rig} {style}, one run-length string per",
                 "-- 768 x 96 direction strip (row-major; a class letter a-g = 0-6, then the run length when over 1).",
                 "return {"]
        for r, d in enumerate(ROWS):
            lines.append(f'\t{d} = "{rle(classes, r * CELL)}",')
        lines.append("}")
        path = os.path.join(OUT_MAPS, f"{rig}_{style}.luau")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        print("wrote", path, os.path.getsize(path), "bytes")
    names = {C.SKIN: "skin", C.HAIR: "hair", C.OUTFIT: "outfit"}
    index = [
        f"-- GENERATED by Tools/class_maps.py: colour-class maps for the {rig} sheets (Tools/colour_classes.py).",
        "-- Ranges: each recolourable class's brightness range in the drawing (2nd to 98th percentile).",
        "-- Anims without a map here are classified in game by ClassMap.ClassifyUpright.",
        "return {",
        "\tRanges = { " + ", ".join(f"{names[k]} = {{ {lo}, {hi} }}" for k, (lo, hi) in sorted(ranges.items())) + " },",
        "\tAnims = {",
    ]
    for style in pairs:
        index.append(f"\t\t{style} = require(script.Parent.{rig}_{style}),")
    index += ["\t},", "}"]
    with open(os.path.join(OUT_MAPS, f"{rig}.luau"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(index) + "\n")


def main():
    """Since the hairstyles (Tools/hair_wire.py), the bodies are bald and their class maps come from the hairstyle
    build; this only writes the colour sets. --legacy rebuilds the old haired sheets' maps (Art/Sprites) for reference."""
    if "--legacy" not in sys.argv[1:]:
        write_data()
        return
    write_female = "--write-female" in sys.argv[1:]
    os.makedirs(OUT_MAPS, exist_ok=True)
    with tempfile.TemporaryDirectory() as scratch:
        src = os.path.join(scratch, "src")
        with zipfile.ZipFile(ZIP) as z:
            z.extractall(src)
        for root, _, files in os.walk(src):
            if any(f.endswith("_frame01.png") for f in files):
                src = root
                break
        female_src = os.path.join(scratch, "female")
        subprocess.run([sys.executable, os.path.join(HERE, "female.py"), src, female_src], check=True,
                       stdout=subprocess.DEVNULL)
        write_maps("humanm", build("humanm", src, scratch, False))
        write_maps("humanf", build("humanf", female_src, scratch, write_female))
    write_data()


if __name__ == "__main__":
    main()
