"""Build the game data for character customization.

    python Tools/class_maps.py

1. Rebuilds walk, run and dodge from Art/Source/cf_human_m_full_rags_walk_v2.zip with colour classes
   (Tools/walk_cycle.py --classes), and checks each rebuilt sheet is identical to the uploaded one in Art/Sprites.
2. Writes src/ReplicatedStorage/Crownfall/Render/ClassMaps/humanm*.luau: one run-length class map per direction
   strip, plus each class's brightness range.
3. Writes src/ReplicatedStorage/Crownfall/Shared/AppearanceData.luau from Art/Sprites/palettes.json.
"""
import os
import subprocess
import sys
import tempfile
import zipfile

from PIL import Image

import colour_classes as C
import recolour

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
ZIP = os.path.join(ROOT, "Art", "Source", "cf_human_m_full_rags_walk_v2.zip")
SHEETS = os.path.join(ROOT, "Art", "Sprites", "humanm")
OUT_MAPS = os.path.join(ROOT, "src", "ReplicatedStorage", "Crownfall", "Render", "ClassMaps")
OUT_DATA = os.path.join(ROOT, "src", "ReplicatedStorage", "Crownfall", "Shared", "AppearanceData.luau")
ROWS = ["S", "SW", "W", "NW", "N", "NE", "E", "SE"]
STYLES = ["walk", "run", "dodge"]
CELL = 96
LETTERS = "abcdefg"  # class 0..6


def rle(classes, top):
    """One 768 x 96 strip, row-major: a class letter, then the run length when more than 1 ('a12c3e')."""
    px = classes.load()
    out, prev, n = [], None, 0
    for y in range(top, top + CELL):
        for x in range(classes.width):
            k = px[x, y]
            if k == prev:
                n += 1
                continue
            if prev is not None:
                out.append(LETTERS[prev] + (str(n) if n > 1 else ""))
            prev, n = k, 1
    out.append(LETTERS[prev] + (str(n) if n > 1 else ""))
    return "".join(out)


def build(src, scratch):
    pairs = {}
    for style in STYLES:
        sheet_out = os.path.join(scratch, f"{style}.png")
        class_out = os.path.join(scratch, f"{style}_classes.png")
        subprocess.run([sys.executable, os.path.join(HERE, "walk_cycle.py"), src, sheet_out, "--style", style,
                        "--classes", class_out], check=True, stdout=subprocess.DEVNULL)
        built = Image.open(sheet_out).convert("RGBA")
        uploaded = Image.open(os.path.join(SHEETS, f"cf_humanm_full_rags_{style}.png")).convert("RGBA")
        assert built.tobytes() == uploaded.tobytes(), f"{style}: rebuilt sheet differs from the uploaded one"
        with Image.open(class_out) as im:
            pairs[style] = (uploaded, im.copy())
    return pairs


def lua_ramp(ramp):
    return "{ " + ", ".join(f"Color3.fromRGB({r}, {g}, {b})" for r, g, b in ramp) + " }"


def write_data():
    pal = recolour.load_palettes()
    lines = [
        "-- GENERATED by Tools/class_maps.py from Art/Sprites/palettes.json. Do not edit by hand.",
        "-- Curated colour sets for character customization; each ramp runs dark to light.",
        "return {",
    ]
    for slot in ("skin", "hair", "outfit"):
        lines.append(f"\t{slot} = {{")
        for e in pal[slot]:
            orig = ", Original = true" if e.get("original") else ""
            lines.append(f'\t\t{{ Id = "{e["id"]}", Name = "{e["name"]}"{orig}, Ramp = {lua_ramp(e["ramp"])} }},')
        lines.append("\t},")
    lines.append("}")
    with open(OUT_DATA, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT_DATA)


def main():
    os.makedirs(OUT_MAPS, exist_ok=True)
    with tempfile.TemporaryDirectory() as scratch:
        src = os.path.join(scratch, "src")
        with zipfile.ZipFile(ZIP) as z:
            z.extractall(src)
        # the zip may hold the frames in a subfolder
        for root, _, files in os.walk(src):
            if any(f.endswith("_frame01.png") for f in files):
                src = root
                break
        pairs = build(src, scratch)
    ranges = recolour.stats(pairs.values())
    for style, (sheet, classes) in pairs.items():
        lines = [f"-- GENERATED by Tools/class_maps.py: colour classes for humanm {style}, one run-length string per",
                 "-- 768 x 96 direction strip (row-major; a class letter a-g = 0-6, then the run length when over 1).",
                 "return {"]
        for r, d in enumerate(ROWS):
            lines.append(f'\t{d} = "{rle(classes, r * CELL)}",')
        lines.append("}")
        path = os.path.join(OUT_MAPS, f"humanm_{style}.luau")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        print("wrote", path, os.path.getsize(path), "bytes")
    names = {C.SKIN: "skin", C.HAIR: "hair", C.OUTFIT: "outfit"}
    index = [
        "-- GENERATED by Tools/class_maps.py: colour-class maps for the humanm sheets (Tools/colour_classes.py).",
        "-- Ranges: each recolourable class's brightness range in the drawing (2nd to 98th percentile).",
        "-- Anims without a map here (idle) are classified in game by ClassMap.ClassifyUpright.",
        "return {",
        "\tRanges = { " + ", ".join(f"{names[k]} = {{ {lo}, {hi} }}" for k, (lo, hi) in sorted(ranges.items())) + " },",
        "\tAnims = {",
    ]
    for style in STYLES:
        index.append(f"\t\t{style} = require(script.Parent.humanm_{style}),")
    index += ["\t},", "}"]
    with open(os.path.join(OUT_MAPS, "humanm.luau"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(index) + "\n")
    write_data()


if __name__ == "__main__":
    main()
