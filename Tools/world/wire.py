"""Wire a built map (Tools/world/mirefen.py output) into the game.

    python Tools/world/wire.py export <build_dir> <MapName>          # upload files -> E:/Crownfall/Uploads/<MapName>
    python Tools/world/wire.py wire <build_dir> <MapName> <ids.json>  # -> Shared/Maps/<MapName>.luau

ids.json maps each uploaded file name (without .png) to its asset id.
"""
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
MAPS = os.path.join(ROOT, "src", "ReplicatedStorage", "Crownfall", "Shared", "Maps")


def files(build, name):
    """[(upload name, source path)] for a built map."""
    with open(os.path.join(build, "map.json")) as f:
        meta = json.load(f)
    out = []
    for c in meta["chunks"]:
        if c["water"]:  # an animated tile: the whole tile in 4 frames, ripples painted in
            for fr in range(4):
                out.append((f"{name} Ground {c['cx']}-{c['cz']} {fr + 1}", os.path.join(build, f"ground_{c['cx']}_{c['cz']}_{fr}.png")))
        else:
            out.append((f"{name} Ground {c['cx']}-{c['cz']}", os.path.join(build, f"ground_{c['cx']}_{c['cz']}.png")))
    for i in range(meta["atlases"]):
        out.append((f"{name} Props {i + 1}", os.path.join(build, f"props_{i}.png")))
    return meta, out


def export(build, name):
    dest = f"E:/Crownfall/Uploads/{name}"
    os.makedirs(dest, exist_ok=True)
    _, fl = files(build, name)
    for upload, src in fl:
        shutil.copy(src, os.path.join(dest, upload + ".png"))
    print("wrote", dest, len(fl), "files")


def wire(build, name, ids_path):
    meta, fl = files(build, name)
    with open(ids_path, encoding="utf-8") as f:
        ids = json.load(f)
    rid = lambda n: f"rbxassetid://{ids[n]}"
    order = sorted(meta["kinds"])
    lines = [f"-- GENERATED by Tools/world/wire.py from the {name} build (Tools/world/). Do not edit by hand.",
             "-- Ground in tiles (opaque, 1-4 frames: water tiles ripple), prop kinds (atlas frames [atlas, x, y, w, h]),",
             "-- and placements packed as \"kind index,x,y;\" in map pixels (Render/World).",
             "return {", f'\tName = "{name}",', f"\tSize = Vector2.new({meta['size'][0]}, {meta['size'][1]}),",
             f"\tChunk = {meta['chunk']},", "\tChunks = {"]
    for c in meta["chunks"]:
        if c["water"]:
            names = [f"{name} Ground {c['cx']}-{c['cz']} {k + 1}" for k in range(4)]
        else:
            names = [f"{name} Ground {c['cx']}-{c['cz']}"]
        frames = ", ".join(f'"{rid(n)}"' for n in names)
        lines.append(f'\t\t{{ cx = {c["cx"]}, cz = {c["cz"]}, Frames = {{ {frames} }} }},')
    lines += ["\t},", "\tAtlases = { " + ", ".join(f'"{rid(f"{name} Props {i + 1}")}"' for i in range(meta["atlases"])) + " },",
              "\tKindOrder = { " + ", ".join(f'"{k}"' for k in order) + " },", "\tKinds = {"]
    for k in order:
        kd = meta["kinds"][k]
        frames = ", ".join("{ " + ", ".join(str(v) for v in r) + " }" for r in kd["frames"])
        lines.append(f'\t\t{k} = {{ Frames = {{ {frames} }}, FPS = {kd["fps"]}, Block = {kd["block"]}, Decal = {str(kd["decal"]).lower()} }},')
    index = {k: i + 1 for i, k in enumerate(order)}
    packed = ";".join(f"{index[p]},{x},{y}" for p, x, y in meta["props"])
    lines += ["\t},", f'\tProps = "{packed}",', "}"]
    os.makedirs(MAPS, exist_ok=True)
    path = os.path.join(MAPS, f"{name}.luau")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    if sys.argv[1] == "export":
        export(sys.argv[2], sys.argv[3])
    else:
        wire(sys.argv[2], sys.argv[3], sys.argv[4])
